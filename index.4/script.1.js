    /** API proxy — المفاتيح على السيرفر فقط، المتصفح يكلم /api/ */
    /* Defense-in-depth: server already sets Cache-Control: no-store, but
       we also pass cache:'no-store' + a per-request cache buster so no
       intermediate (browser HTTP cache, service worker, etc.) can serve
       a stale count. */
    function apiNoCacheUrl(path) {
      return path + (path.includes("?") ? "&" : "?") + "_=" + Date.now();
    }

    /** أرقام المنصة من /api/stats — ال Worker يقرأها من Supabase بمفاتيح السيرفر */
    async function fetchPlatformStats() {
      try {
        const res = await fetch(apiNoCacheUrl("/api/stats"), { cache: "no-store" });
        if (!res.ok) return null;
        const data = await res.json();
        return data && typeof data === "object" ? data : null;
      } catch { return null; }
    }

