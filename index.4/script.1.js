    function formatPlatformStatDisplay(n) {
      if (n == null || !Number.isFinite(Number(n)) || Number(n) < 0) return "0";
      const v = Math.floor(Number(n));
      const l = lang();
      const loc = (l === "ar" || l === "ur") ? "ar-SA" : l === "fr" ? "fr-FR" : "en-US";
      try {
        return new Intl.NumberFormat(loc, { numberingSystem: "latn" }).format(v);
      } catch {
        return String(v);
      }
    }

    function parsePlatformStatNumberFromText(s) {
      if (s == null || s === "") return 0;
      const digits = String(s).replace(/\D/g, "");
      if (!digits) return 0;
      const n = parseInt(digits, 10);
      return Number.isFinite(n) ? n : 0;
    }

    const platformStatAnimGeneration = new Map();

    function animatePlatformStatElementToNumber(el, toNum) {
      const id = el.id;
      if (!id) {
        el.textContent = formatPlatformStatDisplay(toNum);
        return;
      }
      let gen = platformStatAnimGeneration.get(id) || 0;
      gen += 1;
      platformStatAnimGeneration.set(id, gen);

      const fromNum = parsePlatformStatNumberFromText(el.textContent);
      if (fromNum === toNum) {
        el.textContent = formatPlatformStatDisplay(toNum);
        el.classList.remove("platform-stat-value--counting");
        return;
      }

      el.classList.add("platform-stat-value--counting");
      const delta = Math.abs(toNum - fromNum);
      const dir = toNum > fromNum ? 1 : -1;

      /* فرق صغير: عداد خطوة بخطوة (إحساس سينمائي واضح) */
      if (delta > 0 && delta <= 80) {
        let cur = fromNum;
        const msPerStep = Math.min(48, Math.max(22, Math.floor(560 / delta)));
        function stepOnce() {
          if (platformStatAnimGeneration.get(id) !== gen) return;
          cur += dir;
          el.textContent = formatPlatformStatDisplay(cur);
          if (cur === toNum) {
            if (platformStatAnimGeneration.get(id) === gen) {
              el.classList.remove("platform-stat-value--counting");
              platformStatAnimGeneration.delete(id);
            }
            return;
          }
          window.setTimeout(stepOnce, msPerStep);
        }
        window.setTimeout(stepOnce, msPerStep);
        return;
      }

      const duration = Math.min(1200, Math.max(340, Math.pow(delta, 0.42) * 32));
      const t0 = performance.now();

      function easeOutQuint(t) {
        return 1 - Math.pow(1 - t, 5);
      }

      function tick(now) {
        if (platformStatAnimGeneration.get(id) !== gen) return;
        const u = Math.min(1, (now - t0) / duration);
        const e = easeOutQuint(u);
        const cur = Math.round(fromNum + (toNum - fromNum) * e);
        el.textContent = formatPlatformStatDisplay(cur);
        if (u < 1) {
          requestAnimationFrame(tick);
        } else {
          el.textContent = formatPlatformStatDisplay(toNum);
          if (platformStatAnimGeneration.get(id) === gen) {
            el.classList.remove("platform-stat-value--counting");
            platformStatAnimGeneration.delete(id);
          }
        }
      }
      requestAnimationFrame(tick);
    }

    function applyPlatformStatsToDom(data, opts) {
      const flash = opts && opts.flash;
      const animateNumbers = opts && opts.animateNumbers;
      const pairs = [
        ["statValueOrgs", "organizations"],
        ["statValueTrackers", "trackers"],
        ["statValueItems", "items"],
        ["statItemsUpcoming", "itemsUpcoming"],
        ["statItemsOverdue", "itemsOverdue"],
        ["statItemsDone", "itemsDone"],
        ["statValueNotifs", "notifications"],
        ["statNotifEmail", "notifEmail"],
        ["statNotifTelegram", "notifTelegram"],
        ["statNotifWhatsapp", "notifWhatsapp"],
        ["statNotifSms", "notifSms"]
      ];
      pairs.forEach(([id, key]) => {
        const el = document.getElementById(id);
        if (!el) return;
        const toNum =
          !data || data[key] == null ? 0 : Math.floor(Number(data[key]));
        const safeTo = Number.isFinite(toNum) && toNum >= 0 ? toNum : 0;
        const nextText = formatPlatformStatDisplay(safeTo);
        if (flash && el.textContent !== nextText) {
          el.classList.remove("platform-stat-value--pulse");
          void el.offsetWidth;
          el.classList.add("platform-stat-value--pulse");
        }
        if (animateNumbers) {
          animatePlatformStatElementToNumber(el, safeTo);
        } else {
          el.textContent = nextText;
          el.classList.remove("platform-stat-value--counting");
        }
      });
    }

